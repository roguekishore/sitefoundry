// Builds public/r/ from every item: r/<name>.json (latest), r/<name>/<version>.json (immutable),
// r/index.json; plus the @foundry/* path map used by TypeScript, the gallery and check.
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import semver from "semver";
import { SCHEMA, hashFiles, type IndexEntry, type RegistryItem } from "@foundry/core";
import { REGISTRY_DIR, ROOT, propsOf, scan, type ScannedItem } from "./lib/scan.ts";

export async function writePathMap(items: ScannedItem[]): Promise<void> {
  const map = Object.fromEntries(items.filter((i) => i.meta.entry).map((i) => [i.name, `${i.dir}/${i.meta.entry}`]));
  await writeFile(join(ROOT, "foundry.paths.json"), JSON.stringify(map, null, 2) + "\n");
  const paths = Object.fromEntries(Object.entries(map).map(([name, path]) => [`@foundry/${name}`, [`./${path}`]]));
  await writeFile(
    join(ROOT, "tsconfig.paths.json"),
    JSON.stringify({ "//": "generated by tools/build-registry.ts", compilerOptions: { paths } }, null, 2) + "\n",
  );
}

export function toRegistryItem(item: ScannedItem): RegistryItem {
  const { demo: _demo, ...meta } = item.meta;
  const props = ["block", "component"].includes(meta.type) ? propsOf(join(ROOT, item.dir, meta.entry)) : undefined;
  return {
    ...meta,
    source: meta.source ?? "foundry",
    name: item.name,
    files: item.files,
    dependencies: item.dependencies,
    registryDependencies: item.imports.foundry,
    ...(props ? { props } : {}),
    hash: hashFiles(item.files),
  };
}

/** Versions already built for an item, and the hash each was built with. */
async function builtVersions(name: string): Promise<Map<string, string>> {
  const dir = join(REGISTRY_DIR, name);
  const out = new Map<string, string>();
  if (!existsSync(dir)) return out;
  for (const f of await readdir(dir)) {
    if (!f.endsWith(".json")) continue;
    const built = JSON.parse(await readFile(join(dir, f), "utf8")) as RegistryItem;
    out.set(built.version, built.hash);
  }
  return out;
}

/** Errors that stop an item from being built: a changed version, or a version going backwards. */
export async function versionErrors(item: ScannedItem): Promise<string[]> {
  if (!semver.valid(item.meta.version)) return [`version "${item.meta.version}" is not a valid semver version`];
  const built = await builtVersions(item.name);
  const hash = hashFiles(item.files);
  const sameVersion = built.get(item.meta.version);
  if (sameVersion && sameVersion !== hash) {
    return [`files changed but version is still ${item.meta.version}; bump "version" in meta.json (built versions never change)`];
  }
  const newest = [...built.keys()].filter((v) => semver.valid(v)).sort(semver.rcompare)[0];
  if (newest && semver.lt(item.meta.version, newest)) {
    return [`version ${item.meta.version} is older than the built ${newest}`];
  }
  return [];
}

async function main() {
  const items = await scan();
  const failed: string[] = [];
  const names = new Map<string, string>();
  for (const item of items) {
    const errs = [...item.errors];
    if (names.has(item.name)) errs.push(`name already used by ${names.get(item.name)}`);
    names.set(item.name, item.dir);
    errs.push(...(await versionErrors(item)));
    if (errs.length) failed.push(`${item.dir}\n  ${errs.join("\n  ")}`);
  }
  await writePathMap(items);
  if (failed.length) {
    console.error(`registry not built:\n${failed.join("\n")}`);
    process.exit(1);
  }

  await mkdir(REGISTRY_DIR, { recursive: true });
  const index: IndexEntry[] = [];
  for (const item of items) {
    const built = toRegistryItem(item);
    const json = JSON.stringify(built, null, 2) + "\n";
    await mkdir(join(REGISTRY_DIR, item.name), { recursive: true });
    const versionFile = join(REGISTRY_DIR, item.name, `${built.version}.json`);
    if (!existsSync(versionFile)) await writeFile(versionFile, json);
    await writeFile(join(REGISTRY_DIR, `${item.name}.json`), json);

    const { files, ...rest } = built;
    const versions = [...(await builtVersions(item.name)).keys()].sort(semver.compare);
    index.push({ ...rest, files: files.map((f) => f.path), path: item.dir, versions });
  }
  await writeFile(join(REGISTRY_DIR, "index.json"), JSON.stringify({ schema: SCHEMA, items: index }, null, 2) + "\n");
  console.log(`registry built: ${items.length} items → public/r/`);
}

if (process.argv[1]?.replace(/\\/g, "/").endsWith("tools/build-registry.ts")) await main();
