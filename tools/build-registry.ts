// Builds a target's registry: public/r/<name>.json (latest), public/r/<name>/<version>.json
// (immutable), public/r/index.json; plus the @foundry/* path map used by TypeScript, the gallery
// and check. `pnpm build:registry` builds the foundry's, `pnpm build:registry:vault` the vault's.
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import semver from "semver";
import { SCHEMA, hashItem, type IndexEntry, type RegistryItem } from "@foundry/core";
import { own, propsOf, scan, targetFromArgs, type ScannedItem, type Target } from "./lib/scan.ts";

/** foundry.paths.json and tsconfig.paths.json at the target's root: item name → its entry. */
export async function writePathMap(t: Target, items: ScannedItem[]): Promise<void> {
  const map = Object.fromEntries(items.filter((i) => i.meta.entry).map((i) => [i.name, `${i.dir}/${i.meta.entry}`]));
  await writeFile(join(t.root, "foundry.paths.json"), JSON.stringify(map, null, 2) + "\n");
  const paths = Object.fromEntries(Object.entries(map).map(([name, path]) => [`@foundry/${name}`, [path.startsWith("../") ? path : `./${path}`]]));
  await writeFile(
    join(t.root, "tsconfig.paths.json"),
    JSON.stringify({ "//": "generated by build-registry (the foundry repo's tools/build-registry.ts)", compilerOptions: { paths } }, null, 2) + "\n",
  );
}

export function toRegistryItem(item: ScannedItem): RegistryItem {
  const { demo: _demo, ...meta } = item.meta;
  const props = ["block", "component"].includes(meta.type) ? propsOf(join(item.abs, meta.entry)) : undefined;
  return {
    ...meta,
    source: meta.source ?? "foundry",
    name: item.name,
    files: item.files,
    dependencies: item.dependencies,
    registryDependencies: item.imports.foundry,
    ...(props ? { props } : {}),
    hash: hashItem(item.meta, item.files),
  };
}

/** Versions already built for an item, and the hash each was built with. */
async function builtVersions(t: Target, name: string): Promise<Map<string, string>> {
  const dir = join(t.registryDir, name);
  const out = new Map<string, string>();
  if (!existsSync(dir)) return out;
  for (const f of await readdir(dir)) {
    if (!f.endsWith(".json")) continue;
    const built = JSON.parse(await readFile(join(dir, f), "utf8")) as RegistryItem;
    out.set(built.version, built.hash);
  }
  return out;
}

/** Errors that stop an item from being built: a changed version, or a version going backwards. */
export async function versionErrors(t: Target, item: ScannedItem): Promise<string[]> {
  if (!semver.valid(item.meta.version)) return [`version "${item.meta.version}" is not a valid semver version`];
  const built = await builtVersions(t, item.name);
  const hash = hashItem(item.meta, item.files);
  const sameVersion = built.get(item.meta.version);
  if (sameVersion && sameVersion !== hash) {
    return [`files changed but version is still ${item.meta.version}; bump "version" in meta.json (built versions never change)`];
  }
  const newest = [...built.keys()].filter((v) => semver.valid(v)).sort(semver.rcompare)[0];
  if (newest && semver.lt(item.meta.version, newest)) {
    return [`version ${item.meta.version} is older than the built ${newest}`];
  }
  return [];
}

async function main() {
  const t = targetFromArgs(process.argv.slice(2));
  const all = await scan(t);
  const items = own(all);
  const failed: string[] = [];
  const names = new Map<string, string>();
  for (const item of all) {
    const errs = item.borrowed ? [] : [...item.errors];
    if (names.has(item.name)) errs.push(`name already used by ${names.get(item.name)}`);
    names.set(item.name, item.dir);
    if (!item.borrowed) errs.push(...(await versionErrors(t, item)));
    if (errs.length) failed.push(`${item.dir}\n  ${errs.join("\n  ")}`);
  }
  await writePathMap(t, all);
  if (failed.length) {
    console.error(`registry not built:\n${failed.join("\n")}`);
    process.exit(1);
  }

  await mkdir(t.registryDir, { recursive: true });
  const index: IndexEntry[] = [];
  for (const item of items) {
    const built = toRegistryItem(item);
    const json = JSON.stringify(built, null, 2) + "\n";
    await mkdir(join(t.registryDir, item.name), { recursive: true });
    const versionFile = join(t.registryDir, item.name, `${built.version}.json`);
    if (!existsSync(versionFile)) await writeFile(versionFile, json);
    await writeFile(join(t.registryDir, `${item.name}.json`), json);

    const { files, ...rest } = built;
    const versions = [...(await builtVersions(t, item.name)).keys()].sort(semver.compare);
    index.push({ ...rest, files: files.map((f) => f.path), path: item.dir, versions });
  }
  await writeFile(join(t.registryDir, "index.json"), JSON.stringify({ schema: SCHEMA, items: index }, null, 2) + "\n");
  console.log(`registry built: ${items.length} items → ${relative(process.cwd(), t.registryDir) || t.registryDir}`);
}

if (process.argv[1]?.replace(/\\/g, "/").endsWith("tools/build-registry.ts")) await main();
